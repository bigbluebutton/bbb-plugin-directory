// Builds the BigBlueButton release -> plugin SDK table from the git tags of a
// bigbluebutton/bigbluebutton clone. The SDK version a server compares plugins
// against is `html5PluginSdkVersion` in bigbluebutton.properties; releases that
// predate that property fall back to the SDK dependency of bigbluebutton-html5.

import { execFileSync } from 'node:child_process';
import { compareVersions, isValidVersion, mainVersionOf, normalizeVersion } from './semver.js';

// Plugins exist from 3.0 on; older lines are out of scope.
const MIN_LINE = '3.0.0';

function git(repoDir, args) {
  return execFileSync('git', ['-C', repoDir, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function showFile(repoDir, ref, path) {
  try {
    return git(repoDir, ['show', `${ref}:${path}`]);
  } catch {
    return null;
  }
}

export function sdkVersionAt(repoDir, ref) {
  const properties = showFile(repoDir, ref, 'bigbluebutton-web/grails-app/conf/bigbluebutton.properties');
  const fromProperties = properties?.match(/^html5PluginSdkVersion=(\S+)/m)?.[1];
  if (fromProperties) return normalizeVersion(fromProperties);
  const pkg = showFile(repoDir, ref, 'bigbluebutton-html5/package.json');
  const fromPackage = pkg ? JSON.parse(pkg).dependencies?.['bigbluebutton-html-plugin-sdk'] : null;
  if (fromPackage && isValidVersion(fromPackage.replace(/^v/, ''))) return normalizeVersion(fromPackage);
  return null;
}

/** Stable release tags (vX.Y.Z, no pre-release) from 3.0 on, oldest first. */
export function releaseTags(repoDir) {
  return git(repoDir, ['tag', '--list', 'v*'])
    .split('\n')
    .map((tag) => tag.trim())
    .filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag))
    .filter((tag) => compareVersions(tag.slice(1), MIN_LINE) >= 0)
    .sort((a, b) => compareVersions(a.slice(1), b.slice(1)));
}

/**
 * Regenerates the table, keeping the human-edited fields (`supported`,
 * `minSupported`) of lines that already exist in `previous`.
 */
export function generateSdkTable(repoDir, previous = { lines: {} }) {
  const lines = {};
  for (const tag of releaseTags(repoDir)) {
    const release = tag.slice(1);
    const sdk = sdkVersionAt(repoDir, tag);
    if (!sdk) continue;
    const line = mainVersionOf(release);
    lines[line] ??= {
      supported: previous.lines?.[line]?.supported ?? true,
      minSupported: previous.lines?.[line]?.minSupported ?? release,
      releases: {},
    };
    lines[line].releases[release] = sdk;
  }
  return {
    source: 'Generated by `node src/cli/generate-sdk-table.js` from the release tags of bigbluebutton/bigbluebutton. Only `supported` and `minSupported` are edited by hand.',
    lines,
  };
}
